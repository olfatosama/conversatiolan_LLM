def generate_text(prompt="", max_tokens=300, temperature=0.8, top_k=40):
    if prompt:
        context = torch.tensor([encode(prompt)], dtype=torch.long, device=device)
    else:
        context = torch.zeros((1, 1), dtype=torch.long, device=device)

